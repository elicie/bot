import assert from 'node:assert/strict';
import { test } from 'node:test';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomUUID } from 'node:crypto';
import { Store } from '../server/store';
import type { McpApp } from '../shared/types';

test('legacy Node state reader preserves optional MCP app records without claiming MCP execution', async (t) => {
  const root = await mkdtemp(join(tmpdir(), 'mcp-app-state-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const original = await Store.open(root);
  const bot = original.snapshot().bots[0];
  const statePath = join(root, 'state.json');
  const disk = JSON.parse(await readFile(statePath, 'utf8'));
  const app: McpApp = { botId: bot.id, serverId: randomUUID(), serverUpdatedAt: new Date().toISOString(), server: 'counter', tool: 'counter', uri: 'ui://counter/app', html: '<title>Counter</title><p>counter: 0</p>', input: '{"delta":0}', output: 'counter: 0' };
  disk.conversations.push({ id: randomUUID(), botId: bot.id, title: 'MCP app', updatedAt: new Date().toISOString(), run: { id: randomUUID(), status: 'completed' }, messages: [{ id: randomUUID(), role: 'assistant', text: '', createdAt: new Date().toISOString(), tools: [{ id: randomUUID(), title: 'counter', kind: 'other', status: 'completed', mcpApp: app }] }] });
  await writeFile(statePath, JSON.stringify(disk));
  const loaded = await Store.open(root);
  assert.deepEqual(loaded.snapshot().conversations[0].messages[0].tools[0].mcpApp, app);
  await loaded.changed();
  assert.deepEqual(JSON.parse(await readFile(statePath, 'utf8')).conversations[0].messages[0].tools[0].mcpApp, app);
  const secret = 'quoted-key-"-\\-value';
  disk.settings.apiKey = secret;
  const encodedInput = JSON.stringify({ [secret]: { token: secret }, literal: 'ordinary' }).replaceAll('q', '\\u0071');
  disk.conversations[0].messages[0].tools[0].mcpApp.input = encodedInput;
  await writeFile(statePath, JSON.stringify(disk));
  const privateLoaded = await Store.open(root);
  const publicInput = JSON.parse(privateLoaded.snapshot().conversations[0].messages[0].tools[0].mcpApp!.input);
  assert.deepEqual(publicInput, { '[redacted]': { token: '[redacted]' }, literal: 'ordinary' });
  assert.equal(privateLoaded.conversations[0].messages[0].tools[0].mcpApp!.input, encodedInput);
  disk.conversations[0].messages[0].tools[0].mcpApp.input = JSON.stringify({ [secret]: 1, '[redacted]': 2 });
  await writeFile(statePath, JSON.stringify(disk));
  assert.equal((await Store.open(root)).snapshot().conversations[0].messages[0].tools[0].mcpApp!.input, '{}');
  disk.conversations[0].messages[0].tools[0].mcpApp.html = '한'.repeat(66_667);
  await writeFile(statePath, JSON.stringify(disk));
  await assert.rejects(Store.open(root), /Cannot load application state/);
});
